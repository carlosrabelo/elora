#pragma once

#include <cstdint>

namespace elora {
namespace font {

// 5x7 glyphs; bit 4 is the leftmost column.
const std::uint8_t kDigit[10][7] = {
    {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E},
    {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E},
    {0x0E, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1F},
    {0x0E, 0x11, 0x01, 0x06, 0x01, 0x11, 0x0E},
    {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02},
    {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E},
    {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E},
    {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08},
    {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E},
    {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C},
};
const std::uint8_t kF[7] = {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10};
const std::uint8_t kP[7] = {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10};
const std::uint8_t kS[7] = {0x0E, 0x11, 0x10, 0x0E, 0x01, 0x11, 0x0E};

inline const std::uint8_t* glyph_rows(char c) {
    if (c >= '0' && c <= '9') {
        return kDigit[c - '0'];
    }
    if (c == 'F' || c == 'f') {
        return kF;
    }
    if (c == 'P' || c == 'p') {
        return kP;
    }
    if (c == 'S' || c == 's') {
        return kS;
    }
    return nullptr;
}

}  // namespace font
}  // namespace elora
